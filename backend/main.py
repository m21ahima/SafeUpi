# --------------------------------------------------------------------
# Auth: signup / login / OTP verification. Simple email+password+OTP
# flow - see auth.py for the hashing/OTP helpers and notifications.py
# for how the OTP actually gets "sent" (simulated unless you plug in a
# real SMS/email provider).
# --------------------------------------------------------------------

class SignupRequest(BaseModel):
    name: str
    email: str
    mobile: str
    password: str


class LoginRequest(BaseModel):
    email: str
    password: str
    captcha_id: str
    captcha_answer: str


class VerifyOtpRequest(BaseModel):
    identifier: str  # email used at signup, or login
    code: str
    purpose: str  # 'signup' | 'login'


class ResendOtpRequest(BaseModel):
    identifier: str
    purpose: str


class ForgotPasswordRequest(BaseModel):
    email: str


class ResetPasswordRequest(BaseModel):
    email: str
    code: str
    new_password: str


@app.get("/api/auth/captcha")
def get_captcha():
    """A fresh captcha challenge for the login form. One-time use - call
    this again to get a new one after a failed attempt."""
    return auth.generate_captcha()


@app.post("/api/auth/signup")
def signup(body: SignupRequest):
    # Check both email AND mobile for duplicates, reported as one clear
    # message (avoids a raw database error reaching the user).
    if database.get_user_by_email(body.email) or database.get_user_by_mobile(body.mobile):
        raise HTTPException(
            status_code=400,
            detail="An account with this email or mobile number already exists.",
        )
    if len(body.password) < 6:
        raise HTTPException(status_code=400, detail="Password must be at least 6 characters.")

    password_hash, salt = auth.hash_password(body.password)
    user_id = database.create_user(body.name, body.email, body.mobile, password_hash, salt)
    # No OTP step at signup - the account is usable immediately. OTP is
    # only required at login (acts as 2FA on every sign-in instead).
    database.mark_user_verified(user_id)

    return {"user_id": user_id, "message": "Account created successfully. Please log in."}


@app.post("/api/auth/login")
def login(body: LoginRequest):
    if not auth.verify_captcha(body.captcha_id, body.captcha_answer):
        raise HTTPException(status_code=400, detail="Incorrect captcha. Please try again.")

    user = database.get_user_by_email(body.email)
    if not user or not auth.verify_password(body.password, user["password_hash"], user["password_salt"]):
        raise HTTPException(status_code=401, detail="Invalid email or password.")

    code = auth.generate_otp()
    database.insert_otp(user["email"], code, "login", auth.otp_expiry(), user_id=user["id"])
    notifications.send_otp(user["email"], code, "login", user.get("mobile"))

    response = {"user_id": user["id"], "message": "OTP sent to verify this login."}
    if notifications.EMAIL_PROVIDER != "smtp":
        response["demo_otp"] = code
    return response


@app.post("/api/auth/verify-otp")
def verify_otp(body: VerifyOtpRequest):
    otp_row = database.get_latest_otp(body.identifier, body.purpose)
    if not otp_row:
        raise HTTPException(status_code=400, detail="No OTP was requested for this identifier.")
    if auth.is_otp_expired(otp_row["expires_at"]):
        raise HTTPException(status_code=400, detail="This OTP has expired. Request a new one.")
    if otp_row["code"] != body.code:
        raise HTTPException(status_code=400, detail="Incorrect OTP.")

    database.consume_otp(otp_row["id"])
    user = database.get_user_by_id(otp_row["user_id"])
    if body.purpose == "signup":
        database.mark_user_verified(user["id"])

    return {
        "verified": True,
        "user": {"id": user["id"], "name": user["name"], "email": user["email"], "mobile": user["mobile"]},
    }


@app.post("/api/auth/resend-otp")
def resend_otp(body: ResendOtpRequest):
    code = auth.generate_otp()
    existing = database.get_latest_otp(body.identifier, body.purpose)
    user_id = existing["user_id"] if existing else None
    database.insert_otp(body.identifier, code, body.purpose, auth.otp_expiry(), user_id=user_id)
    user = database.get_user_by_email(body.identifier) if "@" in body.identifier else None
    notifications.send_otp(
        body.identifier if "@" in body.identifier else (user["email"] if user else None),
        code,
        body.purpose,
        user.get("mobile") if user else None,
    )

    response = {"message": "A new OTP has been sent."}
    if notifications.EMAIL_PROVIDER != "smtp":
        response["demo_otp"] = code
    return response


@app.post("/api/auth/forgot-password")
def forgot_password(body: ForgotPasswordRequest):
    user = database.get_user_by_email(body.email)
    # Always return the same response to avoid exposing whether an email exists.
    if user:
        code = auth.generate_otp()
        database.insert_otp(body.email, code, "password_reset", auth.otp_expiry(), user_id=user["id"])
        notifications.send_otp(body.email, code, "password reset", user.get("mobile"))
    return {"message": "If an account exists for this email, a reset OTP has been sent."}


@app.post("/api/auth/reset-password")
def reset_password(body: ResetPasswordRequest):
    if len(body.new_password) < 6:
        raise HTTPException(status_code=400, detail="Password must be at least 6 characters.")
    otp_row = database.get_latest_otp(body.email, "password_reset")
    if not otp_row:
        raise HTTPException(status_code=400, detail="No password reset OTP was requested.")
    if auth.is_otp_expired(otp_row["expires_at"]):
        raise HTTPException(status_code=400, detail="This OTP has expired. Request a new one.")
    if otp_row["code"] != body.code:
        raise HTTPException(status_code=400, detail="Incorrect OTP.")
    password_hash, salt = auth.hash_password(body.new_password)
    database.update_user_password(otp_row["user_id"], password_hash, salt)
    database.consume_otp(otp_row["id"])
    return {"message": "Password reset successfully. You can now log in."}


# --------------------------------------------------------------------
# Payment limits (requested in the college project brief):
#   - a hard min/max per transaction
#   - a per-category cap (bigger categories can move more money)
#   - a rolling daily cap across all transactions
# --------------------------------------------------------------------
MIN_TRANSACTION_AMOUNT = 100
MAX_TRANSACTION_AMOUNT = 1_000_000
DAILY_TRANSACTION_LIMIT = 300_000

CATEGORY_LIMITS = {
    "Food": 10_000,
    "Shopping": 50_000,
    "Bills": 100_000,
    "Travel": 200_000,
    "Healthcare": 300_000,
    "Education": 500_000,
    "Transfer": 1_000_000,
}


class LockConfirmationRequest(BaseModel):
    transaction_id: int
    tx_hash: str
    sender_address: str


class DirectPaymentConfirmationRequest(BaseModel):
    transaction_id: int
    tx_hash: str
    sender_address: str
    recipient_address: str


class EscrowActionRequest(BaseModel):
    transaction_id: int
    tx_hash: str  # the on-chain release/refund tx MetaMask returned


# --------------------------------------------------------------------
# 1. Analyze a payment - the core endpoint
# --------------------------------------------------------------------
@app.post("/api/analyze-payment")
def analyze_payment(payment: PaymentRequest):
    transaction = payment.model_dump()
    amount = transaction["amount"]

    # ---- limit checks (run before the ML model even sees the payment) ----
    if amount < MIN_TRANSACTION_AMOUNT:
        raise HTTPException(
            status_code=400,
            detail=f"Minimum transfer amount is ₹{MIN_TRANSACTION_AMOUNT:,}.",
        )
    if amount > MAX_TRANSACTION_AMOUNT:
        raise HTTPException(
            status_code=400,
            detail=f"Maximum transfer amount is ₹{MAX_TRANSACTION_AMOUNT:,}.",
        )

    category = transaction.get("category")
    category_cap = CATEGORY_LIMITS.get(category)
    if category_cap is not None and amount > category_cap:
        raise HTTPException(
            status_code=400,
            detail=f"'{category}' payments are capped at ₹{category_cap:,} each.",
        )

    today_total = database.get_today_total(transaction.get("user_id"))
    if today_total + amount > DAILY_TRANSACTION_LIMIT:
        remaining = max(0, DAILY_TRANSACTION_LIMIT - today_total)
        raise HTTPException(
            status_code=400,
            detail=(
                f"Daily transaction limit of ₹{DAILY_TRANSACTION_LIMIT:,} reached. "
                f"You have ₹{remaining:,.0f} left today."
            ),
        )

    risk = ml_model.get_risk_score(transaction)

    if risk["level"] in ("HIGH", "MALICIOUS"):
        # High/malicious risk -> the payment is NOT sent. It waits for the
        # sender's wallet to lock the funds on-chain (see
        # /api/lock-confirmation) before it's actually held in escrow.
        status = "escrow_pending"
    else:
        # LOW/MEDIUM/MEDIUM-HIGH still get sent on-chain and still require
        # the sender to confirm the payment themselves in MetaMask - they
        # just aren't routed through the escrow contract. This waits for
        # /api/direct-payment-confirmation once that transfer confirms.
        status = "direct_pending"

    transaction_id = database.insert_transaction(
        recipient=transaction["recipient"],
        amount=transaction["amount"],
        category=transaction.get("category"),
        note=transaction.get("note"),
        risk_score=risk["score"],
        risk_level=risk["level"],
        status=status,
        user_id=transaction.get("user_id"),
        sender_email=transaction.get("sender_email"),
        sender_mobile=transaction.get("sender_mobile"),
    )

    # Notify the user immediately that the payment has entered processing.
    # Final success/refund notifications are sent only after on-chain verification.
    # Do not send a payment notification while it is only being analyzed.
    # Email/SMS for a payment is sent only after on-chain completion below.

    return {
        "transaction_id": transaction_id,
        "risk_score": risk["score"],
        "risk_level": risk["level"],
        "message": risk["message"],
        "status": status,
        "requires_escrow": status == "escrow_pending",
        "requires_direct_confirmation": status == "direct_pending",
        "is_malicious": risk["level"] == "MALICIOUS",
        "amount_wei": str(blockchain.rupees_to_wei(transaction["amount"])),
    }


# --------------------------------------------------------------------
# 2. Record + verify the on-chain escrow lock (called after MetaMask's
#    lockFunds() transaction confirms in the browser)
# --------------------------------------------------------------------
@app.post("/api/lock-confirmation")
def lock_confirmation(body: LockConfirmationRequest):
    txn = database.get_transaction_by_id(body.transaction_id)
    if not txn:
        raise HTTPException(status_code=404, detail="Transaction not found")
    if txn["status"] != "escrow_pending":
        raise HTTPException(status_code=400, detail="Transaction is not awaiting an escrow lock")

    expected_wei = blockchain.rupees_to_wei(txn["amount"])
    try:
        result = blockchain.verify_lock_transaction(
            tx_hash=body.tx_hash,
            expected_sender=body.sender_address,
            expected_amount_wei=expected_wei,
        )
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))

    escrow_id = str(result["escrow_id"])
    database.set_transaction_escrow(
        transaction_id=body.transaction_id,
        escrow_id=escrow_id,
        tx_hash=body.tx_hash,
        sender_address=body.sender_address,
    )
    # Escrow is not a successful payment, so no success notification is sent here.

    return {"transaction_id": body.transaction_id, "status": "escrow", "escrow_id": escrow_id}


# --------------------------------------------------------------------
# 2b. Record + verify a direct (non-escrow) on-chain payment - for
#     LOW/MEDIUM/MEDIUM-HIGH risk transactions. These are still signed
#     and sent by the sender's own MetaMask wallet, just as a plain
#     transfer straight to the recipient instead of through the escrow
#     contract.
# --------------------------------------------------------------------
@app.post("/api/direct-payment-confirmation")
def direct_payment_confirmation(body: DirectPaymentConfirmationRequest):
    txn = database.get_transaction_by_id(body.transaction_id)
    if not txn:
        raise HTTPException(status_code=404, detail="Transaction not found")
    if txn["status"] != "direct_pending":
        raise HTTPException(status_code=400, detail="Transaction is not awaiting a direct payment")

    expected_wei = blockchain.rupees_to_wei(txn["amount"])
    try:
        blockchain.verify_direct_payment(
            tx_hash=body.tx_hash,
            expected_sender=body.sender_address,
            expected_recipient=body.recipient_address,
            expected_amount_wei=expected_wei,
        )
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))

    database.update_transaction_status(body.transaction_id, "completed", tx_hash=body.tx_hash)
    notifications.notify_transaction_event(database.get_transaction_by_id(body.transaction_id), "completed")

    return {"transaction_id": body.transaction_id, "status": "completed"}


# --------------------------------------------------------------------
# 3. Confirm a held payment ("yes, this was really me")
# --------------------------------------------------------------------
@app.post("/api/confirm-payment")
def confirm_payment(action: EscrowActionRequest):
    txn = database.get_transaction_by_id(action.transaction_id)
    if not txn:
        raise HTTPException(status_code=404, detail="Transaction not found")
    if txn["status"] != "escrow":
        raise HTTPException(status_code=400, detail="Transaction is not in escrow")

    try:
        blockchain.verify_release_transaction(action.tx_hash, int(txn["escrow_id"]))
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))

    database.update_transaction_status(action.transaction_id, "completed", tx_hash=action.tx_hash)
    notifications.notify_transaction_event(database.get_transaction_by_id(action.transaction_id), "completed")

    return {"transaction_id": action.transaction_id, "status": "completed"}


# --------------------------------------------------------------------
# 4. Cancel a held payment (user cancels, or cooling-off timer runs out)
# --------------------------------------------------------------------
@app.post("/api/cancel-payment")
def cancel_payment(action: EscrowActionRequest):
    txn = database.get_transaction_by_id(action.transaction_id)
    if not txn:
        raise HTTPException(status_code=404, detail="Transaction not found")
    if txn["status"] != "escrow":
        raise HTTPException(status_code=400, detail="Transaction is not in escrow")

    try:
        blockchain.verify_refund_transaction(action.tx_hash, int(txn["escrow_id"]))
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))

    database.update_transaction_status(action.transaction_id, "refunded", tx_hash=action.tx_hash)
    # A refund is not a successful outgoing payment; no success notification is sent.

    return {"transaction_id": action.transaction_id, "status": "refunded"}


